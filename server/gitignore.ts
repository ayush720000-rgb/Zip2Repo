/**
 * Builds a .gitignore for an uploaded project that does not have one.
 * Keeps dependencies, build output, caches, and local secrets out of Git.
 */

const NODE_RULES = ['node_modules/', 'dist/', 'build/', '.next/', 'out/', 'npm-debug.log*', 'yarn-error.log*'];
const PYTHON_RULES = ['__pycache__/', '*.py[cod]', '.venv/', 'venv/', '.pytest_cache/', 'build/', 'dist/'];
const COMMON_RULES = ['.DS_Store', 'Thumbs.db', '.env', '.env.*.local', '*.log'];

export function buildGitignore(projectType: string): string {
  const language = projectType === 'python' ? PYTHON_RULES : NODE_RULES;
  return [
    '# Generated by Zip2Repo',
    ...language,
    '',
    '# Local files and secrets',
    ...COMMON_RULES,
    '',
  ].join('\n');
}
